def ground(cfg):
    s = cfg['ground_size']
    return f"""    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{s} {s}</size></plane></geometry>
        </collision>
        <visual name="grass">
          <geometry><plane><normal>0 0 1</normal><size>{s} {s}</size></plane></geometry>
          <material>{colour('grass')}</material>
        </visual>
      </link>
    </model>
"""


def surfaces(cfg):
    """Roads, sidewalks, paths, lane markings and zebra crossings as one visual-only model."""
    rects = [tuple(r) for r in cfg['surfaces']]
    w = cfg['sidewalk_width']
    for x0, y0, x1, y1 in cfg['blocks']:
        cx, cy, sx, sy = (x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0
        rects += [(cx, y0 + w / 2, sx, w, 'sidewalk', 2), (cx, y1 - w / 2, sx, w, 'sidewalk', 2),
                  (x0 + w / 2, cy, w, sy, 'sidewalk', 2), (x1 - w / 2, cy, w, sy, 'sidewalk', 2)]

    # Lane markings: dashed centre line on every road, broken at junctions.
    roads = [r for r in cfg['surfaces'] if r[4] == 'asphalt']
    along_x = [r for r in roads if r[2] > r[3]]
    along_y = [r for r in roads if r[3] >= r[2]]
    for cx, cy, sx, sy, *_ in along_x:
        for x in _dashes(cx - sx / 2, cx + sx / 2, [r[0] for r in along_y]):
            rects.append((x, cy, 3.0, 0.15, 'marking', 3))
    for cx, cy, sx, sy, *_ in along_y:
        for y in _dashes(cy - sy / 2, cy + sy / 2, [r[1] for r in along_x]):
            rects.append((cx, y, 0.15, 3.0, 'marking', 3))
    # Zebra crossings on the four approaches of every junction.
    for rx in along_x:
        for ry in along_y:
            jx, jy = ry[0], rx[1]
            if abs(jx - rx[0]) > rx[2] / 2 or abs(jy - ry[1]) > ry[3] / 2:
                continue
            for k in range(-4, 5):
                o = k * 1.2
                rects += [(jx + o, jy + 8.5, 0.6, 3.0, 'marking', 3), (jx + o, jy - 8.5, 0.6, 3.0, 'marking', 3),
                          (jx + 8.5, jy + o, 3.0, 0.6, 'marking', 3), (jx - 8.5, jy + o, 3.0, 0.6, 'marking', 3)]

    out = ['    <model name="city_surfaces">\n      <static>true</static>\n      <link name="link">\n']
    for i, (cx, cy, sx, sy, col, layer) in enumerate(rects):
        out.append(f'        <visual name="s{i}"><pose>{fmt(cx, cy, layer * LAYER_HEIGHT)} 0 0 0</pose>'
                   f'<geometry><box><size>{fmt(sx, sy, 0.002)}</size></box></geometry>'
                   f'<cast_shadows>false</cast_shadows><material>{colour(col)}</material></visual>\n')
    out.append('      </link>\n    </model>\n')
    return ''.join(out)


def _dashes(a, b, junctions, period=6.0, clear=9.0):
    x = a + period / 2
    while x < b - period / 2:
        if all(abs(x - j) > clear for j in junctions):
            yield x
        x += period


def include(name, model, x, y, yaw_deg, z=0.0, static=True):
    st = '<static>true</static>' if static else ''
    return (f'    <include><uri>model://{model}</uri><name>{name}</name>'
            f'<pose>{fmt(x, y, z)} 0 0 {math.radians(yaw_deg):.4f}</pose>{st}</include>\n')


def on_road(cfg, x, y, margin=1.0):
    return any(abs(x - r[0]) < r[2] / 2 + margin and abs(y - r[1]) < r[3] / 2 + margin
               for r in cfg['surfaces'] if r[4] == 'asphalt')


def static_models(cfg, rng):
    out, counts = [], {}

    def add(model, x, y, yaw):
        k = counts[model] = counts.get(model, -1) + 1
        out.append(include(f'{model}_{k}', model, x, y, yaw))

    for m, x, y, yaw in cfg['buildings'] + cfg['props']:
        add(m, x, y, yaw)

    for m, x0, y0, x1, y1, spacing in cfg['rows']:
        n = int(math.hypot(x1 - x0, y1 - y0) // spacing)
        for i in range(n + 1):
            x, y = x0 + (x1 - x0) * i / max(n, 1), y0 + (y1 - y0) * i / max(n, 1)
            if not on_road(cfg, x, y):
                add(m, x, y, rng.uniform(0, 360))

    for sc in cfg['scatter']:
        placed, tries = [], 0
        x0, y0, x1, y1 = sc['region']
        while len(placed) < sc['count'] and tries < 5000:
            tries += 1
            x, y = rng.uniform(x0, x1), rng.uniform(y0, y1)
            if any(a <= x <= c and b <= y <= d for a, b, c, d in sc.get('keep_out', [])):
                continue
            if any(math.hypot(x - px, y - py) < sc['min_gap'] for px, py in placed):
                continue
            placed.append((x, y))
            add(sc['model'], x, y, rng.uniform(0, 360))

    offsets = cfg.get('vehicle_heading_offset', {})
    for m, x, y, yaw in cfg['parked']:
        add(m, x, y, yaw + offsets.get(m, 0.0))
    return ''.join(out)


def traffic_models(cfg):
    """Moving cars start at their route position; traffic_node animates them by name."""
    t = cfg['traffic']
    offsets = cfg.get('vehicle_heading_offset', {})
    routes = {k: Route(rounded_loop(v, t['corner_radius'])) for k, v in t['routes'].items()}
    out = []
    for i, (model, route, _speed, frac) in enumerate(t['vehicles']):
        r = routes[route]
        x, y, yaw = r.pose_at(frac * r.length)
        out.append(include(f'traffic_{i}', model, x, y, math.degrees(yaw) + offsets.get(model, 0.0)))
    return ''.join(out)


def drone(cfg):
    x, y, yaw = cfg['drone_spawn']
    return include('drone', 'x500_tracker', x, y, yaw, z=0.25, static=False)


# --------------------------------------------------------------------------- people

def recolour(dae, shirt, pants, skin):
    """Swap the diffuse colour of the sweater / jeans / skin materials in a COLLADA file."""
    def sub(kind, rgb, text):
        pat = re.compile(r'(<effect id="[^"]*' + kind + r'[^"]*-effect">.*?<diffuse>\s*<color[^>]*>)'
                         r'([^<]+)(</color>)', re.S)
        return pat.sub(lambda m: m.group(1) + fmt(*rgb) + ' 1' + m.group(3), text, count=1)
    for kind, rgb in (('sweater', shirt), ('jeans', pants), ('skin', skin)):
        dae = sub(kind, rgb, dae)
    return dae


def people(cfg, assets, rng):
    pc = cfg['people']
    root = os.path.join(assets, 'models', 'people')
    os.makedirs(os.path.join(root, 'meshes'), exist_ok=True)
    with open(os.path.join(root, 'model.config'), 'w') as f:
        f.write('<?xml version="1.0"?>\n<model><name>people</name><version>1.0</version>'
                '<sdf version="1.9">model.sdf</sdf><description>Recoloured animated humans '
                '(generated)</description></model>\n')
    with open(os.path.join(root, 'model.sdf'), 'w') as f:
        f.write('<?xml version="1.0"?>\n<sdf version="1.9"><model name="people"><static>true</static>'
                '<link name="l"/></model></sdf>\n')
    sources = {}

    def mesh_for(i, anim):
        if anim not in sources:
            with open(os.path.join(root, 'source', f'{anim}.dae')) as f:
                sources[anim] = f.read()
        pal = pc['palette']
        dae = recolour(sources[anim], rng.choice(pal['shirt']), rng.choice(pal['pants']),
                       rng.choice(pal['skin']))
        name = f'{anim}_{i:02d}.dae'
        with open(os.path.join(root, 'meshes', name), 'w') as f:
            f.write(dae)
        return f'model://people/meshes/{name}'

    actors = []   # (anim, waypoints)
    for w in pc['walkers']:
        start = rng.randrange(len(w['path'])) if w['mode'] == 'loop' else 0
        actors.append((w['anim'], walking_waypoints(w['path'], w['speed'], w['mode'], start_index=start)))
    for wd in pc['wanderers']:
        x0, y0, x1, y1 = wd['region']
        for _ in range(wd['count']):
            cx, cy = rng.uniform(x0 + 10, x1 - 10), rng.uniform(y0 + 10, y1 - 10)
            n = wd['points']
            pts = []
            for k in range(n):      # star-shaped random polygon around (cx, cy): never self-intersects
                a = 2 * math.pi * (k + rng.uniform(-0.3, 0.3)) / n
                r = rng.uniform(6, 16)
                pts.append((min(max(cx + r * math.cos(a), x0), x1), min(max(cy + r * math.sin(a), y0), y1)))
            if rng.random() < 0.5:
                pts.reverse()
            actors.append(('walk', walking_waypoints(pts, rng.uniform(*wd['speed']), 'loop')))
    for idle in pc['idle']:
        yaw = math.radians(idle['yaw'])
        actors.append((idle['anim'], [(0.0, idle['x'], idle['y'], yaw), (30.0, idle['x'], idle['y'], yaw)]))

    out = []
    for i, (anim, wps) in enumerate(actors):
        uri = mesh_for(i, anim)
        out.append(f'    <actor name="person_{i:02d}">\n'
                   f'      <skin><filename>{uri}</filename><scale>1.0</scale></skin>\n'
                   f'      <animation name="{anim}"><filename>{uri}</filename>'
                   f'<interpolate_x>{"true" if anim in ("walk", "run") else "false"}</interpolate_x></animation>\n'
                   f'      <script><loop>true</loop><delay_start>0</delay_start><auto_start>true</auto_start>\n'
                   f'        <trajectory id="0" type="{anim}" tension="0.6">\n')
        for t, x, y, yaw in wps:
            out.append(f'          <waypoint><time>{t:.2f}</time><pose>{fmt(x, y, ACTOR_Z)} 0 0 {yaw:.4f}</pose></waypoint>\n')
        out.append('        </trajectory>\n      </script>\n    </actor>\n')
    return ''.join(out), len(actors)


# --------------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--config', required=True)
    ap.add_argument('--assets', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    with open(a.config) as f:
        cfg = yaml.safe_load(f)
    rng = random.Random(cfg['seed'])

    people_sdf, n_people = people(cfg, a.assets, rng)
    sdf = ''.join([header(cfg), ground(cfg), surfaces(cfg), static_models(cfg, rng),
                   traffic_models(cfg), drone(cfg), people_sdf, '  </world>\n</sdf>\n'])
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write(sdf)
    print(f'[build_world] wrote {a.out}: {n_people} people, '
          f'{len(cfg["traffic"]["vehicles"])} moving + {len(cfg["parked"])} parked vehicles')


if __name__ == '__main__':
    main()
