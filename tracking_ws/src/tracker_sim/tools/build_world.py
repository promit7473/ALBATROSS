import math
import os
import random
import re
import sys

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from tracker_sim.paths import Route, rounded_loop, walking_waypoints  # noqa: E402

COLOURS = {
    'grass': (0.33, 0.47, 0.22),
    'asphalt': (0.17, 0.17, 0.18),
    'asphalt_light': (0.30, 0.30, 0.31),
    'paving': (0.63, 0.61, 0.57),
    'sidewalk': (0.56, 0.56, 0.55),
    'marking': (0.92, 0.92, 0.88),
}
LAYER_HEIGHT = 0.004          # vertical separation between surface layers [m]
ACTOR_Z = 1.0                 # actor meshes have their origin at the hips


def fmt(*v):
    return ' '.join(f'{x:.4g}' for x in v)


def colour(name_or_rgb):
    r, g, b = COLOURS[name_or_rgb] if isinstance(name_or_rgb, str) else name_or_rgb
    return f'<ambient>{fmt(r, g, b)} 1</ambient><diffuse>{fmt(r, g, b)} 1</diffuse>' \
           f'<specular>0.05 0.05 0.05 1</specular>'


# --------------------------------------------------------------------------- world parts

